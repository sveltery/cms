import {readFile,rename,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {build} from 'vite';

const target=process.argv[2];
if(target!=='node'&&target!=='cloudflare')throw new Error('Select node or cloudflare revision maintenance');
const root=fileURLToPath(new URL('../',import.meta.url));
const worker=target==='cloudflare';
const output=resolve(root,'build',worker?'cloudflare':'node');

// This independent server library build consumes the same reviewed modules.
// Node leaves runtime dependencies external for the frozen production install;
// Wrangler consumes the self-contained Worker library beside the official entry.
await build({
  configFile:false,root,logLevel:'warn',
  plugins:worker?[{
    name:'sveltery-maintenance-cloudflare-storage',
    resolveId(source,importer) {
      if(source==='../runtime/node.ts'&&importer?.endsWith('/maintenance/runtime.ts')) {
        return resolve(root,'src/lib/server/runtime/node-cloudflare.ts');
      }
    }
  }]:[],
  ssr:worker?{noExternal:true}:{},
  build:{ssr:true,target:'es2022',outDir:output,emptyOutDir:false,
    rollupOptions:{input:resolve(root,'src/lib/server/maintenance/runtime.ts'),external:[/^node:/],
      output:{inlineDynamicImports:true,entryFileNames:'maintenance.js'}}}
});

if(worker) {
  const entry=resolve(output,'worker.js');
  const original=await readFile(entry,'utf8');
  if(original.includes('// Sveltery revision-maintenance wrapper')) {
    throw new Error('Rebuild the official Cloudflare adapter before wrapping maintenance');
  }
  // Keep the generated adapter imports relative to their original directory.
  // Its complete fetch handler and manifest remain generated by the adapter.
  await rename(entry,resolve(output,'kit-worker.js'));
  await writeFile(entry,`// Sveltery revision-maintenance wrapper\nimport app from './kit-worker.js';\nimport {createRevisionMaintenanceScheduledHandler} from './maintenance.js';\nexport default {...app,...createRevisionMaintenanceScheduledHandler()};\n`);
}
