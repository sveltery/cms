// Native inline fallback preparation, using the exact already frozen compiler.
// This generates no public locale catalog and does not load/activate i18n.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { CALENDAR_MESSAGE_DESCRIPTORS } from '../src/lib/calendar/message-descriptors.ts';

const require = createRequire(import.meta.url);
const coreRequire = createRequire(require.resolve('@lingui/core/package.json'));
const { compileMessageOrThrow } = coreRequire('@lingui/message-utils/compileMessage');
const output = new URL('../src/lib/calendar/message-fallbacks.ts', import.meta.url);
const compiled = Object.fromEntries(Object.entries(CALENDAR_MESSAGE_DESCRIPTORS)
  .map(([message, descriptor]) => [message, compileMessageOrThrow(descriptor.message)]));
const content = '// Deterministic Native English fallback arrays; generated by frozen Lingui5.9.5.\n' +
  '// Exact source descriptors remain in message-descriptors.ts; no catalog is activated.\n' +
  'export const CALENDAR_MESSAGE_FALLBACKS = ' + JSON.stringify(compiled, null, 2) + ' as const;\n';
if (process.argv.includes('--verify')) {
  if (readFileSync(output, 'utf8') !== content) throw new Error('Calendar English fallback vector differs');
} else writeFileSync(output, content);
console.log(JSON.stringify({ descriptors: Object.keys(compiled).length, bytes: Buffer.byteLength(content),
  sha256: createHash('sha256').update(content).digest('hex'), compiler: coreRequire.resolve('@lingui/message-utils/compileMessage') }));
